export interface EmbedDocInput {
  name: string; // scene folder
  title: string;
  runtimeSrc: string; // URL of agent3d-runtime.js as written in the snippet
  sceneSrc: string; // URL of scene.json as written in the snippet
  posterSrc?: string;
  aspect: string; // "4:1"
  snippet: string;
  dataKeys: string[]; // scene.data keys usable as data-* attributes
  integrity?: string;
  ogImage?: string;
  hasScripts: boolean;
  credits: string[];
  version?: string;
}

const kebab = (k: string) => k.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);

// ─── React / Next.js ────────────────────────────────────────────────────

export function reactWrapper(d: EmbedDocInput): string {
  return `"use client";
// Agent3DScene.tsx — React (and Next.js) wrapper for the <agent3d-scene> Web Component.
// Generated by \`agent3d export\` for "${d.title}". No dependency besides React (>= 17).
//
//   import { Agent3DScene } from "./Agent3DScene";
//   <Agent3DScene src="${d.sceneSrc}" poster=${JSON.stringify(d.posterSrc ?? "")} aspect="${d.aspect}"
//                 data={{ ${d.dataKeys[0] ? `${d.dataKeys[0]}: "…"` : "title: \"…\""} }} onSceneEvent={(e) => console.log(e.name)} />
//
// Next.js: this file is a client component ("use client"); the runtime is loaded
// in the browser only (a <script type="module"> added once), so it is SSR-safe.
// Copy the export's agent3d-runtime/ and ${d.name}/ folders into public/.
import { createElement, useEffect, useRef, type CSSProperties } from "react";

export const AGENT3D_RUNTIME_SRC = ${JSON.stringify(d.runtimeSrc)};

export interface Agent3DPlayer {
  play(): void;
  pause(): void;
  seek(t: number): Promise<void>;
  time(): number;
  snapshot(type?: "image/png" | "image/webp", quality?: number): string;
  state(): Record<string, unknown>;
}

export interface Agent3DSceneElement extends HTMLElement {
  player: Agent3DPlayer | null;
  ready: Promise<Agent3DPlayer>;
  readonly data: Record<string, unknown>;
  play(): void;
  pause(): void;
  seek(t: number): Promise<void>;
  setData(values: Record<string, unknown>, opts?: { replace?: boolean }): Promise<void>;
  trigger(name: string, payload?: unknown): void;
  reload(): Promise<void>;
}

export interface Agent3DSceneProps {
  src: string;
  poster?: string;
  aspect?: string;
  alt?: string;
  ariaLabel?: string;
  // Values for {data.key} placeholders of the scene (texts, links) — applied live.
  data?: Record<string, string | number | boolean>;
  autoplay?: boolean;
  paused?: boolean;
  loop?: boolean | "pingpong";
  quality?: "low" | "medium" | "high" | "auto";
  interactive?: boolean;
  runtimeSrc?: string;
  className?: string;
  style?: CSSProperties;
  onReady?(el: Agent3DSceneElement): void;
  onError?(issue: { code: string; message: string; path?: string }): void;
  onSceneEvent?(e: { name: string; payload?: unknown }): void;
  onSceneClick?(e: { id: string | null; x: number; y: number }): void;
}

function loadRuntime(src: string): void {
  if (typeof window === "undefined" || window.customElements?.get("agent3d-scene")) return;
  const abs = new URL(src, document.baseURI).href;
  if ([...document.querySelectorAll<HTMLScriptElement>("script[type=module]")].some((s) => s.src === abs)) return;
  const s = document.createElement("script");
  s.type = "module";
  s.src = abs;${d.integrity ? `\n  if (src === AGENT3D_RUNTIME_SRC) s.integrity = ${JSON.stringify(d.integrity)};` : ""}
  document.head.appendChild(s);
}

export function Agent3DScene(props: Agent3DSceneProps) {
  const ref = useRef<Agent3DSceneElement | null>(null);
  const handlers = useRef(props);
  handlers.current = props;
  const runtimeSrc = props.runtimeSrc ?? AGENT3D_RUNTIME_SRC;

  useEffect(() => loadRuntime(runtimeSrc), [runtimeSrc]);

  useEffect(() => {
    const el = ref.current;
    if (!el) return;
    const on = (type: string, fn: (detail: never) => void) => {
      const l = (e: Event) => fn((e as CustomEvent).detail as never);
      el.addEventListener(type, l);
      return () => el.removeEventListener(type, l);
    };
    const offs = [
      on("agent3d:ready", () => handlers.current.onReady?.(el)),
      on("agent3d:error", (d) => handlers.current.onError?.(d)),
      on("agent3d:event", (d) => handlers.current.onSceneEvent?.(d)),
      on("agent3d:click", (d) => handlers.current.onSceneClick?.(d)),
    ];
    return () => offs.forEach((off) => off());
  }, []);

  const dataJson = JSON.stringify(props.data ?? {});
  useEffect(() => {
    const el = ref.current;
    if (el && typeof el.setData === "function" && props.data) void el.setData(props.data);
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [dataJson]);

  const attrs: Record<string, unknown> = {
    ref,
    src: props.src,
    poster: props.poster,
    aspect: props.aspect,
    alt: props.alt,
    "aria-label": props.ariaLabel,
    class: props.className,
    style: props.style,
    autoplay: props.autoplay === false ? "false" : undefined,
    paused: props.paused ? "" : undefined,
    loop: props.loop === undefined ? undefined : String(props.loop),
    quality: props.quality,
    interactive: props.interactive === false ? "false" : undefined,
  };
  // Initial data as data-* attributes (bound before the first frame, SSR-friendly).
  for (const [k, v] of Object.entries(props.data ?? {})) attrs[\`data-\${k.replace(/[A-Z]/g, (c) => "-" + c.toLowerCase())}\`] = String(v);
  return createElement("agent3d-scene", attrs);
}

export default Agent3DScene;
`;
}

